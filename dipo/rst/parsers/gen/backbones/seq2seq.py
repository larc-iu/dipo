"""Encoder-decoder backbone: the source document is encoded once, the linearized
tree is generated by the decoder attending to it (cross-attention). Two streams,
no single-stream separator (unlike `decoder_only`).

The decode I/O rides a compound cache `{enc_out, attn_mask, past}`: `seed` encodes
the source once and expands it to the beam count, `advance` steps the decoder
attending to the cached encoder outputs, and only the decoder `past` reorders on a
beam step (the K encoder rows are identical, so reordering them is a no-op).
"""

import logging

import torch
import torch.nn as nn
from transformers import AutoModelForSeq2SeqLM, AutoTokenizer
from transformers.modeling_outputs import BaseModelOutput

from dipo.common.log import warn
from dipo.rst.parsers.common.seqgen import warm_init_head
from dipo.rst.parsers.gen.backbones.base import Backbone
from dipo.rst.parsers.gen.errors import OverLengthError

logger = logging.getLogger(__name__)


def probe_enc_specials(tokenizer) -> tuple[list[int], list[int]]:
    """The (prefix, suffix) special tokens `add_special_tokens=True` wraps content
    with. Probing once lets the encoder input be rebuilt from the align_edus source
    subwords so it matches `tokenizer(text, add_special_tokens=True)` token-for-token,
    across families, without the removed `build_inputs_with_special_tokens`.

    Families differ in BOTH size and side: T5 appends EOS (`[], [1]`), T5Gemma-2
    prepends BOS (`[2], []`), t5gemma-s-s-prefixlm wraps with nothing (`[], []`).
    """
    inner = tokenizer("test", add_special_tokens=False)["input_ids"]
    outer = tokenizer("test", add_special_tokens=True)["input_ids"]
    i = next((j for j in range(len(outer) - len(inner) + 1) if outer[j : j + len(inner)] == inner), None)
    if i is None:
        raise RuntimeError("Could not locate the content run inside add_special_tokens=True output.")
    return list(outer[:i]), list(outer[i + len(inner) :])


def strip_enc_wrapper(ids: list[int], prefix: list[int], suffix: list[int]) -> list[int]:
    """Exact inverse of `_encoder_input_ids`: drop the probed wrapper BY POSITION.

    Not by token identity: a tokenizer can set `bos_token_id` while prepending
    nothing (t5gemma-s-s-prefixlm), so matching on ids would eat a content token that
    happens to equal bos/eos/pad and shift every COPY cursor against the training
    alignment. The wrapper is whatever the probe found -- possibly empty.
    """
    ids = list(ids)
    if prefix:
        if ids[: len(prefix)] != prefix:
            raise RuntimeError(
                f"Tokenizer output does not start with the probed encoder prefix {prefix}: got {ids[: len(prefix)]}."
            )
        ids = ids[len(prefix) :]
    if suffix:
        if ids[-len(suffix) :] != suffix:
            raise RuntimeError(
                f"Tokenizer output does not end with the probed encoder suffix {suffix}: got {ids[-len(suffix) :]}."
            )
        ids = ids[: -len(suffix)]
    return ids


class Seq2SeqBackbone(Backbone):
    def __init__(self, config):
        super().__init__(config)
        self.decoder_start_token_id: int | None = None
        self._init_tokenizer()
        self._init_model()

    def _init_tokenizer(self) -> None:
        cfg = self.config
        tok = AutoTokenizer.from_pretrained(cfg.model_name)
        if not getattr(tok, "is_fast", False):
            raise RuntimeError(
                f"{cfg.model_name} loaded a slow tokenizer. align_edus_to_tokens needs "
                f"return_offsets_mapping, which only fast (Rust) tokenizers provide."
            )
        if not isinstance(tok.eos_token_id, int):
            raise RuntimeError(f"{cfg.model_name} has eos_token_id={tok.eos_token_id!r}; a single integer EOS is required.")
        if tok.pad_token_id is None:
            tok.pad_token = tok.eos_token
        self.tokenizer = tok
        self.stream_end_id = int(tok.eos_token_id)
        try:
            self._enc_prefix_specials, self._enc_suffix_specials = probe_enc_specials(tok)
        except RuntimeError as e:
            raise RuntimeError(f"{cfg.model_name}: {e}") from e
        if cfg.chat_template is not None:
            raise ValueError("chat_template is decoder-only (a causal-stream concept); seq2seq must leave it null.")

    def _init_model(self) -> None:
        cfg = self.config
        # 4-bit QLoRA is only wired for the causal decoder_only backbone (the 70B
        # single-GPU target). Quantizing an encoder-decoder stack is untested here, so
        # refuse it loudly rather than train something unvalidated.
        if cfg.peft is not None and cfg.peft.load_in_4bit:
            raise NotImplementedError(
                "peft.load_in_4bit (4-bit QLoRA) is only supported for backbone='decoder_only'; "
                "the seq2seq backbone has no 4-bit path. Drop load_in_4bit or switch backbones."
            )
        # bf16 master weights are fine under LoRA (adapters train on top); full-FT
        # AdamW on bf16 degenerates, so full-FT loads fp32 (autocast stays bf16).
        model_dtype = torch.bfloat16 if (cfg.amp and cfg.peft is not None) else torch.float32
        model = AutoModelForSeq2SeqLM.from_pretrained(cfg.model_name, dtype=model_dtype)
        # from_pretrained(dtype=...) only PARTIALLY casts t5gemma-2 (a composite
        # encoder/decoder + vision tower): with dtype=float32 ~2/3 of params stay at the
        # checkpoint's stored bf16. Autocast hides the mix at train time, but fp32 eval
        # crashes where a bf16 activation meets an fp32 weight, and full-FT would silently
        # run on bf16 master weights. Force a uniform dtype (.to leaves int buffers alone).
        self.model = model.to(model_dtype)

    def stream_special_tokens(self) -> list[str]:
        # Two streams (encoder + decoder), no single-stream separator to add.
        return []

    PEFT_TASK_TYPE = "SEQ_2_SEQ_LM"

    def _after_add_tokens(self) -> None:
        self.decoder_start_token_id = self._resolve_decoder_start_token_id()

    def _resolve_decoder_start_token_id(self) -> int:
        """Decoder start token, model-family-portable. T5/mT5 expose it on config;
        T5Gemma 2 only via `prepare_decoder_input_ids_from_labels` (prepends BOS).
        Probe config paths, else invoke the HF helper on a stub label, else BOS/pad."""
        for src in (getattr(self.model, "generation_config", None), getattr(self.model, "config", None)):
            tok = getattr(src, "decoder_start_token_id", None) if src is not None else None
            if tok is not None:
                return int(tok)
        prepare = getattr(self.model, "prepare_decoder_input_ids_from_labels", None)
        if prepare is not None:
            stub = torch.zeros((1, 1), dtype=torch.long, device=self.device)
            shifted = prepare(labels=stub) if "labels" in prepare.__code__.co_varnames else prepare(stub)
            return int(shifted[0, 0].item())
        for src in (getattr(self.model, "generation_config", None), getattr(self.model, "config", None)):
            bos = getattr(src, "bos_token_id", None) if src is not None else None
            if bos is not None:
                return int(bos)
        return int(self.tokenizer.pad_token_id)

    def install_head(self, head_spec: dict) -> None:
        """Replace the tied lm_head (Linear(hidden -> full vocab)) with a small fresh
        Linear over the serialization's action vocab. T5Gemma 2 wraps it as
        `lm_head.out_proj`; T5/mT5 expose `lm_head` directly. Rows warm-inited from
        the input embedding (the tied unembedding basis); the head_spec's warm-init
        source is a decoder-only distinction that collapses here (lm_head is tied)."""
        base = self.underlying_model()
        head_vocab_size = head_spec["head_vocab_size"]
        full_id_for_head_idx = head_spec["full_id_for_head_idx"]
        warm_src = base.get_input_embeddings().weight

        if hasattr(base, "lm_head") and hasattr(base.lm_head, "out_proj") and isinstance(base.lm_head.out_proj, nn.Linear):
            old = base.lm_head.out_proj
            new = nn.Linear(old.in_features, head_vocab_size, bias=False).to(dtype=old.weight.dtype, device=old.weight.device)
            warm_init_head(new, warm_src, full_id_for_head_idx)
            base.lm_head.out_proj = new
        elif hasattr(base, "lm_head") and isinstance(base.lm_head, nn.Linear):
            old = base.lm_head
            new = nn.Linear(old.in_features, head_vocab_size, bias=False).to(dtype=old.weight.dtype, device=old.weight.device)
            warm_init_head(new, warm_src, full_id_for_head_idx)
            base.lm_head = new
        else:
            raise RuntimeError(
                f"Don't know how to replace lm_head on {type(base).__name__}. "
                f"Expected `lm_head` as Linear or `lm_head.out_proj` as Linear."
            )
        logger.info(f"Replaced lm_head with fresh Linear(hidden={old.in_features}, head_vocab_size={head_vocab_size}).")

    # underlying_model / enable_grad_checkpointing / set_grad_checkpointing /
    # cache_configs / device / inference_mode are shared on the Backbone base.

    # ---- packaging + forward ----

    def _encoder_input_ids(self, source_ids: list[int]) -> list[int]:
        """The encoder input: the source content subwords wrapped with the family's
        prefix/suffix specials (probed at construction), reproducing
        `tokenizer(text, add_special_tokens=True)` for the align_edus content."""
        return [*self._enc_prefix_specials, *source_ids, *self._enc_suffix_specials]

    def pack_example(self, source_ids, seen_tokens, label_tokens, *, scores_separator: bool = False):
        """Two aligned decoder streams plus the encoder input. `labels` are the
        targets (terminator appended); `decoder_input_ids` are shift_right(seen) with
        the decoder-start token at position 0 (COPY positions already substituted to
        source subwords in `seen`). `scores_separator` is a decoder-only concept
        (there is no in-stream SEP here) and is ignored."""
        del scores_separator
        cfg = self.config
        input_ids = self._encoder_input_ids(source_ids)
        if len(input_ids) > cfg.max_input_length:
            warn(
                f"Source side overflowed: {len(input_ids)} > max_input_length={cfg.max_input_length}. "
                f"Tree cannot be encoded (training raises on this)."
            )
            return None
        seen = [*seen_tokens, self.stream_end_id]
        label = [*label_tokens, self.stream_end_id]
        if len(label) > cfg.max_output_length:
            warn(
                f"Target side overflowed: {len(label)} > max_output_length={cfg.max_output_length}. "
                f"Tree cannot be encoded (training raises on this)."
            )
            return None
        decoder_input_ids = [self.decoder_start_token_id, *seen[:-1]]
        return {
            "input_ids": input_ids,
            "attention_mask": [1] * len(input_ids),
            "decoder_input_ids": decoder_input_ids,
            "labels": label,
        }

    def collate(self, examples, pad_id):
        # examples: list of {input_ids, attention_mask, decoder_input_ids, labels} dicts.
        B = len(examples)
        enc_len = max(len(e["input_ids"]) for e in examples)
        dec_len = max(len(e["labels"]) for e in examples)
        input_ids = torch.full((B, enc_len), pad_id, dtype=torch.long)
        attention_mask = torch.zeros((B, enc_len), dtype=torch.long)
        decoder_input_ids = torch.full((B, dec_len), pad_id, dtype=torch.long)
        labels = torch.full((B, dec_len), -100, dtype=torch.long)
        for i, e in enumerate(examples):
            ne, nd = len(e["input_ids"]), len(e["labels"])
            input_ids[i, :ne] = torch.tensor(e["input_ids"], dtype=torch.long)
            attention_mask[i, :ne] = torch.tensor(e["attention_mask"], dtype=torch.long)
            decoder_input_ids[i, :nd] = torch.tensor(e["decoder_input_ids"], dtype=torch.long)
            labels[i, :nd] = torch.tensor(e["labels"], dtype=torch.long)
        return {
            "input_ids": input_ids,
            "attention_mask": attention_mask,
            "decoder_input_ids": decoder_input_ids,
            "labels": labels,
        }

    def forward_logits(self, batch):
        """Encoder-decoder teacher-forced pass. `decoder_input_ids` already carry the
        shift-right, so logits and labels align 1:1 (no causal slice, unlike
        decoder_only)."""
        out = self.model(
            input_ids=batch["input_ids"],
            attention_mask=batch["attention_mask"],
            decoder_input_ids=batch["decoder_input_ids"],
            return_dict=True,
        )
        return out.logits, batch["labels"]

    # ---- decode I/O ----

    def tokenize_source(self, text: str) -> list[int]:
        """The content subwords the COPY cursor tracks (the probed wrapper removed, so
        they match the align_edus training slices). Raises OverLengthError if the doc
        doesn't fit; a truncated source silently corrupts the metric (see errors.py).

        The budget is checked on the WRAPPED length, exactly what `pack_example` checks
        at training. Assuming a fixed one re-added token instead would admit a document
        that overflows once wrapped, on any tokenizer that wraps on both sides."""
        cap = self.config.max_input_length
        enc = self.tokenizer(text, add_special_tokens=True, truncation=False)
        ids = strip_enc_wrapper(enc["input_ids"], self._enc_prefix_specials, self._enc_suffix_specials)
        n_wrapped = len(self._encoder_input_ids(ids))
        if n_wrapped > cap:
            raise OverLengthError(
                f"Source overflowed at inference: {n_wrapped} > max_input_length={cap} subwords "
                f"({len(ids)} content + {n_wrapped - len(ids)} special). "
                f"Bump max_input_length to fit the longest document, then re-run."
            )
        return ids

    def decode_prefix(self, source_ids: list[int]) -> list[int]:
        return self._encoder_input_ids(source_ids)

    def seed(self, prefix_ids, num_rows: int = 1):
        """Encode the source once, expand to `num_rows` beams, run the first decoder
        step from the decoder-start token. Returns `(logits, cache)` where the cache
        is compound (encoder outputs + attention mask + decoder past); `logits` is
        `[head_V]` for a single row, `[num_rows, head_V]` for beams."""
        device = self.device
        enc_input = torch.tensor([prefix_ids], dtype=torch.long, device=device)
        enc_attn = torch.ones_like(enc_input)
        encoder = self.model.get_encoder()
        enc_out = encoder(input_ids=enc_input, attention_mask=enc_attn, return_dict=True)
        hidden = enc_out.last_hidden_state.expand(num_rows, -1, -1).contiguous()
        attn_mask = enc_attn.expand(num_rows, -1).contiguous()
        enc_out_rows = BaseModelOutput(last_hidden_state=hidden)

        decoder_input_ids = torch.full((num_rows, 1), self.decoder_start_token_id, dtype=torch.long, device=device)
        out = self.model(
            encoder_outputs=enc_out_rows,
            attention_mask=attn_mask,
            decoder_input_ids=decoder_input_ids,
            use_cache=True,
            return_dict=True,
        )
        cache = {"enc_out": enc_out_rows, "attn_mask": attn_mask, "past": out.past_key_values}
        logits = out.logits[:, -1, :] if num_rows > 1 else out.logits[0, -1, :]
        return logits, cache

    def advance(self, cache, next_input):
        """One decoder step attending to the cached encoder outputs. `next_input` an
        int (greedy) -> logits [head_V]; a sequence of K ids (beam) -> [K, head_V]."""
        device = self.device
        if isinstance(next_input, int):
            step_input = torch.tensor([[next_input]], dtype=torch.long, device=device)
        else:
            step_input = torch.tensor(list(next_input), dtype=torch.long, device=device).unsqueeze(1)
        out = self.model(
            encoder_outputs=cache["enc_out"],
            attention_mask=cache["attn_mask"],
            decoder_input_ids=step_input,
            past_key_values=cache["past"],
            use_cache=True,
            return_dict=True,
        )
        cache = {**cache, "past": out.past_key_values}
        logits = out.logits[0, -1, :] if isinstance(next_input, int) else out.logits[:, -1, :]
        return logits, cache

    # ---- batched decode I/O (B different documents) ----

    def seed_rows(self, prefix_ids_rows):
        """Encode B different documents in one encoder forward, then run the first
        decoder step for all of them.

        The encoder input is RIGHT-padded: the encoder is bidirectional, so a real
        token's hidden state depends only on the other real tokens the mask admits
        (identical to encoding that document alone), and the pad rows are never
        fully masked (unlike a causal left-pad), so no query row degenerates. The
        decoder needs no padding at all -- every row starts at the same
        decoder-start token and steps in lockstep.
        """
        device = self.device
        pad_id = int(self.tokenizer.pad_token_id)
        B, L = len(prefix_ids_rows), max(len(p) for p in prefix_ids_rows)
        enc_input = torch.full((B, L), pad_id, dtype=torch.long, device=device)
        enc_attn = torch.zeros((B, L), dtype=torch.long, device=device)
        for i, ids in enumerate(prefix_ids_rows):
            enc_input[i, : len(ids)] = torch.tensor(ids, dtype=torch.long, device=device)
            enc_attn[i, : len(ids)] = 1
        enc_out = self.model.get_encoder()(input_ids=enc_input, attention_mask=enc_attn, return_dict=True)
        enc_out_rows = BaseModelOutput(last_hidden_state=enc_out.last_hidden_state)

        decoder_input_ids = torch.full((B, 1), self.decoder_start_token_id, dtype=torch.long, device=device)
        out = self.model(
            encoder_outputs=enc_out_rows,
            attention_mask=enc_attn,
            decoder_input_ids=decoder_input_ids,
            use_cache=True,
            return_dict=True,
        )
        cache = {"enc_out": enc_out_rows, "attn_mask": enc_attn, "past": out.past_key_values}
        return out.logits[:, -1, :], cache

    def advance_rows(self, cache, next_inputs):
        """One decoder step for every row of a `seed_rows` batch. Identical to the
        beam `advance` (the decoder rows are in lockstep either way); the rows just
        cross-attend to B different encoded documents instead of K copies of one."""
        return self.advance(cache, list(next_inputs))

    def beam_reorder_needed(self, step, parents, k, cache):
        from dipo.rst.parsers.common.seqgen import beam_reorder_needed

        # The single doc is encoded once into K identical rows, so only the decoder
        # past needs reordering; the no-op check keys off it.
        return beam_reorder_needed(step, parents, k, cache["past"])

    def reorder_cache(self, cache, parent_tensor):
        from dipo.rst.parsers.common.seqgen import reorder_past_key_values

        past = reorder_past_key_values(cache["past"], parent_tensor, self.underlying_model())
        # enc_out / attn_mask are K identical rows (single-doc beam), so unchanged.
        return {**cache, "past": past}
